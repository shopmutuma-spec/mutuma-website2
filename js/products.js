function normalizeRemoteProduct(product) {
    const currency = product.currency || BASE_CURRENCY;

    return {
        id: product.id,
        name: product.name,
        description: product.description || "",
        category: product.category || "Decor",
        price: toUsdAmount(product.price, currency),
        oldPrice: product.old_price ? toUsdAmount(product.old_price, currency) : null,
        currency: BASE_CURRENCY,
        rating: 4.8,
        reviews: 0,
        stock: product.stock || null,
        images: [product.image_url].filter(Boolean),
        tags: Array.isArray(product.tags) ? product.tags : [],
        featured: Boolean(product.featured),
        adminProduct: true
    };
}

function applyOffer(product, offer) {
    if (!offer || offer.scope !== "all") return product;

    const basePrice = Number(product.basePrice || product._basePrice || product.oldPrice || product.price || 0);
    const discount = Math.max(0, Math.min(Number(offer.discount_percent || 0), 90));
    if (!basePrice || !discount) return product;

    product._basePrice = basePrice;
    product.oldPrice = Math.max(Number(product.oldPrice || 0), basePrice);
    product.price = Number((basePrice * (1 - discount / 100)).toFixed(2));
    product.tags = Array.from(new Set([...(product.tags || []), "offer"]));
    return product;
}

async function fetchStoreCatalog(timeout = 900) {
    const cacheKey = "mutuma.storeCatalog.v2";
    const cacheMaxAge = 10 * 60 * 1000;
    const storage = globalThis.sessionStorage;

    if (storage) {
        try {
            const cached = JSON.parse(storage.getItem(cacheKey) || "null");
            if (cached?.savedAt && Date.now() - cached.savedAt < cacheMaxAge && cached.data) {
                return cached.data;
            }
        } catch (error) {
            storage.removeItem(cacheKey);
        }
    }

    const controller = new AbortController();
    const timeoutId = globalThis.setTimeout(() => controller.abort(), timeout);

    try {
        const response = await fetch("/.netlify/functions/store-catalog", {
            signal: controller.signal,
            cache: "default"
        });
        if (!response.ok) throw new Error("Store catalogue unavailable.");

        const data = await response.json();
        if (storage) {
            storage.setItem(cacheKey, JSON.stringify({
                savedAt: Date.now(),
                data
            }));
        }
        return data;
    } finally {
        globalThis.clearTimeout(timeoutId);
    }
}

export async function loadStoreCatalog() {
    if (catalogLoaded) return products;
    catalogLoaded = true;

    try {
        const data = await fetchStoreCatalog();
        activeStoreOffers = Array.isArray(data.offers) && data.offers.length ? data.offers : [storeSettings.fallbackOffer].filter((offer) => offer?.enabled);
        const remoteProducts = Array.isArray(data.products) ? data.products.map(normalizeRemoteProduct) : [];
        const existingIds = new Set(products.map((product) => product.id));

        remoteProducts.forEach((product) => {
            if (product.images?.[0] && !existingIds.has(product.id)) {
                products.push(product);
                existingIds.add(product.id);
            }
        });

    } catch (error) {
        activeStoreOffers = [storeSettings.fallbackOffer].filter((offer) => offer?.enabled);
    }

    if (activeStoreOffers.length) {
        const fallbackBestOffer = activeStoreOffers
            .filter((offer) => offer.scope === "all")
            .sort((first, second) => Number(second.discount_percent) - Number(first.discount_percent))[0];

        if (fallbackBestOffer) {
            products.forEach((product) => applyOffer(product, fallbackBestOffer));
        }
    }

    return products;
}

