export function getRecommendedProducts(productId, limit = 4) {
    const current = getProductById(productId);
    const currentFamily = productFamily(current);

    return products
        .filter((product) => product.id !== productId)
        .sort((a, b) => {
            const aFamily = currentFamily && productFamily(a) === currentFamily;
            const bFamily = currentFamily && productFamily(b) === currentFamily;
            const aScore = Number(aFamily) * 10 + Number(a.category === current.category) + Number(a.tags.some((tag) => current.tags.includes(tag)));
            const bScore = Number(bFamily) * 10 + Number(b.category === current.category) + Number(b.tags.some((tag) => current.tags.includes(tag)));
            return bScore - aScore;
        })
        .slice(0, limit);
}
